_WORD_SPLIT = re.compile(r"[^а-яёa-z0-9]+")


def _weigh(title: str, body: str,
           markers: tuple[tuple[str, int], ...]) -> int:
    """Сумма весов: в заголовке маркер весит вдвое."""
    total = 0
    for marker, weight in markers:
        if marker in title:
            total += weight * 2
        elif marker in body:
            total += weight
    return total


# Порог, с которого новость считается предупреждением, а не сводкой.
# Одного слова «осторожно» мало — нужны два-три характерных оборота
# либо один сильный («как не стать жертвой», «безопасный счёт»).
# Порог подобран по живым лентам: пост ППС со словом «бдительность»
# не должен считаться предупреждением, а разбор схемы — должен.
PREVENTION_THRESHOLD = 14


def prevention_score(item: RawNewsItem) -> int:
    """Насколько новость похожа на предупреждение о способе обмана."""
    return _weigh((item.title or "").lower(),
                  (item.raw_text or "").lower(), PREVENTION_MARKERS)


def is_prevention(item: RawNewsItem) -> bool:
    """Предупреждение о преступлении — вторая тема канала."""
    return prevention_score(item) >= PREVENTION_THRESHOLD


def score_item(item: RawNewsItem) -> int:
    """
    Балл новости: чем выше, тем раньше её посмотрит модель.

    Заголовок весит вдвое — в лентах МВД суть обычно вынесена именно
    туда, а в теле идут процессуальные подробности, из-за которых
    хорошая история выглядит как сводка.

    Предупреждения о новых способах обмана складываются из тех же слов,
    что и сводки о мошенничестве («мошенники», «кража»), поэтому штраф
    за рутину для них гасится: без этого разбор схемы уходил в хвост
    очереди и до модели не доживал.
    """
    title = (item.title or "").lower()
    body = (item.raw_text or "").lower()

    positive = _weigh(title, body, POSITIVE_MARKERS)
    routine = _weigh(title, body, ROUTINE_MARKERS)
    prevention = _weigh(title, body, PREVENTION_MARKERS)

    score = positive - routine + prevention
    if prevention >= PREVENTION_THRESHOLD:
        # Штраф за «мошенни», «кража», «возбуждено» в предупреждении
        # неизбежен: без этих слов схему не опишешь. Возвращаем его.
        score += routine

    # Слишком короткие заметки — почти всегда анонсы и объявления.
    if len(body) < 300:
        score -= 5

    return score


def rank_candidates(items: list[RawNewsItem]) -> list[RawNewsItem]:
    """
    Сортирует новости от самых перспективных к самым сомнительным.

    Сортировка устойчивая: при равном балле сохраняется исходный
    порядок, в котором первыми идут Telegram-каналы ведомств —
    первоисточники с уже отобранными редакцией историями.
    """
    return sorted(items, key=score_item, reverse=True)


def explain_score(item: RawNewsItem) -> str:
    """Какие слова дали балл — нужно для отладки отбора."""
    text = f"{item.title or ''} {item.raw_text or ''}".lower()
    plus = [m for m, _ in POSITIVE_MARKERS if m in text]
    minus = [m for m, _ in ROUTINE_MARKERS if m in text]
    warn = [m for m, _ in PREVENTION_MARKERS if m in text]
    return (f"балл={score_item(item)} за: {plus[:6]} "
            f"против: {minus[:6]} предупреждение: {warn[:6]}")
