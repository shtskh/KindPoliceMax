_WORD_SPLIT = re.compile(r"[^а-яёa-z0-9]+")


def score_item(item: RawNewsItem) -> int:
    """
    Балл новости: чем выше, тем раньше её посмотрит модель.

    Заголовок весит вдвое — в лентах МВД суть обычно вынесена именно
    туда, а в теле идут процессуальные подробности, из-за которых
    хорошая история выглядит как сводка.
    """
    title = (item.title or "").lower()
    body = (item.raw_text or "").lower()

    score = 0
    for marker, weight in POSITIVE_MARKERS:
        if marker in title:
            score += weight * 2
        elif marker in body:
            score += weight

    for marker, weight in ROUTINE_MARKERS:
        if marker in title:
            score -= weight * 2
        elif marker in body:
            score -= weight

    # Слишком короткие заметки — почти всегда анонсы и объявления.
    if len(body) < 300:
        score -= 5

    return score


def rank_candidates(items: list[RawNewsItem]) -> list[RawNewsItem]:
    """
    Сортирует новости от самых перспективных к самым сомнительным.

    Сортировка устойчивая: при равном балле сохраняется исходный
    порядок, в котором первыми идут Telegram-каналы ведомств —
    первоисточники с уже отобранными редакцией историями.
    """
    return sorted(items, key=score_item, reverse=True)


def explain_score(item: RawNewsItem) -> str:
    """Какие слова дали балл — нужно для отладки отбора."""
    text = f"{item.title or ''} {item.raw_text or ''}".lower()
    plus = [m for m, _ in POSITIVE_MARKERS if m in text]
    minus = [m for m, _ in ROUTINE_MARKERS if m in text]
    return f"балл={score_item(item)} за: {plus[:6]} против: {minus[:6]}"
