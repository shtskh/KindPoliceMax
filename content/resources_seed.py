def build_seed_resources() -> list[PublicResource]:
    """
    Собирает полный справочник в виде списка PublicResource.

    id формируется детерминированно (например, "max_mvd23"), чтобы
    повторный вызов при каждом старте бота не плодил дубликаты: вставка
    идёт с ON CONFLICT(id) DO NOTHING.
    """
    resources: list[PublicResource] = []

    for username, name in TELEGRAM_FEDERAL:
        resources.append(PublicResource(
            id=f"tg_{username}",
            category=ResourceCategory.MVD_TELEGRAM.value,
            region=None,
            name=name,
            url=f"https://t.me/{username}",
        ))

    for handle, name in MAX_FEDERAL:
        resources.append(PublicResource(
            id=f"max_{handle}",
            category=ResourceCategory.MVD_MAX.value,
            region=None,
            name=name,
            url=f"https://max.ru/{handle}",
        ))

    for handle, name, region in MAX_REGIONAL:
        resources.append(PublicResource(
            id=f"max_{handle}",
            category=ResourceCategory.MVD_MAX.value,
            region=region,
            name=name,
            url=f"https://max.ru/{handle}",
        ))

    for index, (name, url, region) in enumerate(INSTITUTES + INSTITUTE_BRANCHES):
        resources.append(PublicResource(
            id=f"edu_{index:03d}",
            category=ResourceCategory.INSTITUTE.value,
            region=region,
            name=name,
            url=url,
        ))

    return resources


def seed_counts() -> dict[str, int]:
    """Сколько записей в каждой категории — для /diag и README."""
    return {
        ResourceCategory.MVD_TELEGRAM.value: len(TELEGRAM_FEDERAL),
        ResourceCategory.MVD_MAX.value: len(MAX_FEDERAL) + len(MAX_REGIONAL),
        ResourceCategory.INSTITUTE.value: len(INSTITUTES) + len(INSTITUTE_BRANCHES),
    }
